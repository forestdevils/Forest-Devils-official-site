const statusConfig = {
    accepted:  { emoji: "🟩", label: "Прийнято" },
    rejected:  { emoji: "🟥", label: "Не прийнято" },
    review:    { emoji: "🟨", label: "На розгляді" },
    cancelled: { emoji: "🟪", label: "Скасовано" }
};

function renderDecisions(filter = "all") {
    const container = document.querySelector(".decisions-list");
    container.innerHTML = "";

    const filtered = filter === "all"
        ? decisions
        : decisions.filter(d => d.status === filter);

    if (filtered.length === 0) {
        container.innerHTML = `<p class="decisions-empty">Рішень не знайдено.</p>`;
        return;
    }

    filtered.forEach(d => {
        const { emoji, label } = statusConfig[d.status];

        let voteHTML = "";
        if (d.vote) {
            const v = d.vote;
            const totalVoted = v.for + v.abstain + v.against;
            const total      = totalVoted + v.notvoted;

            const forPct      = Math.round(v.for     / totalVoted * 100);
            const abstainPct  = Math.round(v.abstain / totalVoted * 100);
            const againstPct  = Math.round(v.against / totalVoted * 100);
            const notvotedPct = Math.round(v.notvoted / total     * 100);

            voteHTML = `
        <div class="decision-vote">
            <div class="vote-bar">
                <div class="vote-segment vote-for"      style="width: ${forPct}%"      title="За: ${forPct}%"></div>
                <div class="vote-segment vote-abstain"  style="width: ${abstainPct}%"  title="Утримались: ${abstainPct}%"></div>
                <div class="vote-segment vote-against"  style="width: ${againstPct}%"  title="Проти: ${againstPct}%"></div>
            </div>
            <div class="vote-labels">
                <span class="vote-label for">✔ За — ${forPct}% (${v.for})</span>
                <span class="vote-label abstain">— Утримались — ${abstainPct}% (${v.abstain})</span>
                <span class="vote-label against">✖ Проти — ${againstPct}% (${v.against})</span>
                <span class="vote-label notvoted">◌ Не голосували — ${notvotedPct}% (${v.notvoted})</span>
            </div>
        </div>
    `;
        }

        const desc = d.description.replace(/\n/g, "<br>");
        const isLong = d.description.length > 300;

        const card = document.createElement("div");
        card.classList.add("decision-card", `status-${d.status}`);
        card.innerHTML = `
            <div class="decision-header">
                <span class="decision-number">${d.number}</span>
                <span class="decision-status">${emoji} ${label}</span>
            </div>
            <h3 class="decision-title">${d.title}</h3>
            <div class="decision-desc-wrapper ${isLong ? "collapsed" : ""}">
                <p class="decision-desc">${desc}</p>
                ${isLong ? `<div class="desc-fade"></div>` : ""}
            </div>
            ${isLong ? `<button class="desc-toggle">Читати більше ▾</button>` : ""}
            ${voteHTML}
        `;

        if (isLong) {
            const btn = card.querySelector(".desc-toggle");
            const wrapper = card.querySelector(".decision-desc-wrapper");
            btn.addEventListener("click", () => {
                const isCollapsed = wrapper.classList.toggle("collapsed");
                btn.textContent = isCollapsed ? "Читати більше ▾" : "Згорнути ▴";
            });
        }

        container.appendChild(card);
    });
}

document.querySelectorAll(".filter-btn").forEach(btn => {
    btn.addEventListener("click", () => {
        document.querySelectorAll(".filter-btn").forEach(b => b.classList.remove("active"));
        btn.classList.add("active");
        renderDecisions(btn.dataset.filter);
    });
});

renderDecisions();